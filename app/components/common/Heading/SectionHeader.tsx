import SectionTag from "./SectionTag";
import HeadingTag from "./HeadingTag";
import { parseMaxW } from "@/lib/utils/cmsMaxWidth";
import { twMerge } from "tailwind-merge";
import { style } from "framer-motion/client";
export interface SectionHeaderData {
  tag: string;
  heading: string;
  highlightLast: number;
  highlight_first?: boolean;
  subhead?: string;
}

type SectionHeaderVariant =
  | "default"
  | "defaultBorder"
  | "subtitle"
  | "subtitleBorder";

interface VariantConfig {
  headingAs: "h1" | "h2" | "h3";
  border: boolean;
  subtitle?: boolean;
  subtitleClass: string;
  highlightColorClass: string;
}

const variants: Record<SectionHeaderVariant, VariantConfig> = {
  default: {
    headingAs: "h2",
    border: false,
    subtitle: false,
    subtitleClass: "max-w-[76ch]",
    highlightColorClass: "text-primary",
  },
  defaultBorder: {
    headingAs: "h2",
    border: true,
    subtitle: false,
    subtitleClass: "max-w-[76ch]",
    highlightColorClass: "text-primary",
  },
  subtitle: {
    headingAs: "h2",
    border: false,
    subtitle: true,
    subtitleClass: "max-w-[76ch]",
    highlightColorClass: "text-primary",
  },
  subtitleBorder: {
    headingAs: "h2",
    border: true,
    subtitle: true,
    subtitleClass: "max-w-[76ch]",
    highlightColorClass: "text-primary",
  },
};

interface SectionHeaderProps {
  data: SectionHeaderData;
  variant?: SectionHeaderVariant;
  headingAs?: VariantConfig["headingAs"];
  subtitleClass?: string;
  subtitleTextClass?: string;
  highlightColorClass?: string;
  className?: string;
}

export default function SectionHeader({
  data,
  variant = "default",
  className,
  subtitleTextClass,
  ...overrides
}: SectionHeaderProps) {
  const config = { ...variants[variant], ...overrides };
  // Arbitrary max-w-[…] values (incl. decimals) typed in the CMS can't be
  // generated by Tailwind, so apply them as inline styles instead.
  const mw = parseMaxW(config.subtitleClass);
  const mwClass = `${mw.rest} ${mw.hasMaxW ? "cms-maxw" : ""}`;
  const mwStyle = mw.style as React.CSSProperties;

  return (
    <div
      className={config.border ? "pb-4 lg:pb-6 border-[#D3D3D3] border-b" : ""}
    >
      {data.tag && <SectionTag text={data.tag} />}

      <div
        className={twMerge(
          `pt-4 xl:pt-6.5 flex ${
            !config.subtitle ? "gap-4 md:gap-6 lg:gap-6" : ""
          } flex-col lg:flex-row justify-between items-baseline lg:items-center`,
          className,
        )}
      >
        <HeadingTag
          as={config.headingAs}
          highlightLast={data.highlightLast}
          highlight_first={data.highlight_first}
          text={data.heading}
          highlightColorClass={config.highlightColorClass}
        />

        {!config.subtitle && (
          <p
            className={`text-18 text-paragraph lg:text-right ${mwClass}`}
            style={mwStyle}
          >
            {data.subhead}
          </p>
        )}
      </div>

      {config.subtitle && data.subhead && (
        <p
          className={`text-paragraph text-18   mt-4 lg:mt-6.5 ${mwClass} ${subtitleTextClass}`}
          style={mwStyle}
          dangerouslySetInnerHTML={{ __html: data.subhead }}
        />
      )}
    </div>
  );
}
